"""Run, pause, resume and inspect DQ agent threads (thread_id = dq:<run_id>:<n>)."""

from collections.abc import Iterator
from contextlib import contextmanager
from typing import Any

from langgraph.checkpoint.postgres import PostgresSaver
from langgraph.types import Command

from pipeline.config import REPO_ROOT, settings
from pipeline.db import transaction
from pipeline.dq_agent.graph import build_graph, initial_state
from pipeline.dq_agent.metrics import latest_agent_run

GRAPH_DOC = REPO_ROOT / "docs" / "dq_agent_graph.md"


@contextmanager
def compiled(client: Any = None, mode: str | None = None) -> Iterator[Any]:
    with PostgresSaver.from_conn_string(settings.database_url) as saver:
        yield build_graph(saver, client=client, mode=mode)


def thread_numbers(run_id: str) -> list[int]:
    with transaction() as conn:
        rows = conn.execute(
            "SELECT DISTINCT thread_id FROM checkpoints WHERE thread_id LIKE %s", (f"dq:{run_id}:%",)
        ).fetchall()
    return sorted(int(r[0].rsplit(":", 1)[1]) for r in rows)


def latest_thread(run_id: str) -> str | None:
    numbers = thread_numbers(run_id)
    return f"dq:{run_id}:{numbers[-1]}" if numbers else None


def config(thread_id: str) -> dict[str, Any]:
    return {"configurable": {"thread_id": thread_id}, "recursion_limit": 200}


def snapshot(graph: Any, thread_id: str) -> dict[str, Any]:
    """Status, pause payload (if paused) and key state values of a thread."""
    state = graph.get_state(config(thread_id))
    values = state.values or {}
    pauses = [i.value for t in state.tasks for i in (t.interrupts or [])]
    status = values.get("status", "unknown")
    if pauses:
        status = pauses[0].get("reason", status)
    return {"thread_id": thread_id, "status": status, "paused": pauses[0] if pauses else None, "next": list(state.next),
            "turns": values.get("turns"), "tool_calls": values.get("tool_calls"),
            "attempts": values.get("attempts"), "validation": values.get("validation")}  # fmt: skip


def run(run_id: str, fresh: bool = False, client: Any = None, mode: str | None = None) -> dict[str, Any]:
    """Start a thread (or continue the latest unfinished one) until it pauses or ends."""
    thread_id = latest_thread(run_id)
    with compiled(client, mode) as graph:
        if thread_id and not fresh:
            current = snapshot(graph, thread_id)
            if current["paused"] or not current["next"]:
                return current | {"note": "thread is paused or finished; use dq-approve / dq-reject, "
                                          "or --fresh for a new attempt"}  # fmt: skip
            graph.invoke(None, config(thread_id))
        else:
            n = (thread_numbers(run_id) or [0])[-1] + 1
            thread_id = f"dq:{run_id}:{n}"
            graph.invoke(initial_state(run_id, thread_id), config(thread_id))
        return snapshot(graph, thread_id)


def resume(run_id: str, payload: dict[str, Any], client: Any = None, mode: str | None = None) -> dict[str, Any]:
    thread_id = latest_thread(run_id)
    if not thread_id:
        raise ValueError(f"no agent thread for run {run_id}; run dq-run first")
    with compiled(client, mode) as graph:
        if not snapshot(graph, thread_id)["paused"]:
            return snapshot(graph, thread_id) | {"note": "thread is not paused"}
        graph.invoke(Command(resume=payload), config(thread_id))
        return snapshot(graph, thread_id)


def status(run_id: str) -> dict[str, Any]:
    thread_id = latest_thread(run_id)
    if not thread_id:
        return {"status": "no agent thread yet"}
    with compiled() as graph:
        return snapshot(graph, thread_id) | {"metrics": latest_agent_run(run_id)}


def write_mermaid() -> str:
    graph = build_graph()
    text = graph.get_graph().draw_mermaid()
    GRAPH_DOC.write_text(f"# DQ agent graph\n\nGenerated by `python -m pipeline.cli dq-graph`.\n\n```mermaid\n{text}```\n")
    return str(GRAPH_DOC)
